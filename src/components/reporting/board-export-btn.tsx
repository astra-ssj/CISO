"use client";

import { useState } from 'react';
import { Button } from '@/components/ui/button';
import { FileDown, Loader2 } from 'lucide-react';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

// Fix TS for autoTable
declare module 'jspdf' {
    interface jsPDF {
        lastAutoTable: { finalY: number };
    }
}

export function BoardReportExport() {
    const [isGenerating, setIsGenerating] = useState(false);

    const generateReport = async () => {
        setIsGenerating(true);

        try {
            // In a real app, we would fetch fresh data here. 
            // For now, we simulate data gathering delay.
            await new Promise(resolve => setTimeout(resolve, 1500));

            const doc = new jsPDF();

            // 1. Header
            doc.setFillColor(20, 20, 20); // Dark background header
            doc.rect(0, 0, 210, 40, 'F');

            doc.setFontSize(22);
            doc.setTextColor(255, 255, 255);
            doc.text('ASTRA | CISO EXECUTIVE BRIEF', 15, 20);

            doc.setFontSize(10);
            doc.setTextColor(156, 163, 175);
            doc.text(`Generated: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}`, 15, 30);
            doc.text('Confidentiality: INTERNAL ONLY', 150, 30);

            // 2. Executive Summary
            let currentY = 50;
            doc.setTextColor(0, 0, 0);
            doc.setFontSize(16);
            doc.text('1. Risk Posture Summary', 15, currentY);

            doc.setFontSize(12);
            doc.text('The organization currently maintains a MODERATE risk posture. Critical vulnerabilities have decreased by 15% WoW.', 15, currentY + 10);

            // 3. KPI Table
            currentY += 25;
            doc.setFontSize(16);
            doc.text('2. Key Performance Indicators', 15, currentY);

            autoTable(doc, {
                startY: currentY + 5,
                head: [['Metric', 'Value', 'Change (WoW)', 'Status']],
                body: [
                    ['Risk Score', '72/100', '-3.2%', 'IMPROVING'],
                    ['Open Criticals', '4', '-2', 'ON TRACK'],
                    ['Mean Time to Resolve', '4.2 Days', '-0.5 Days', 'EXCELLENT'],
                    ['Policy Compliance', '94%', '+1.2%', 'STABLE'],
                ],
                theme: 'grid',
                headStyles: { fillColor: [40, 40, 40] },
                alternateRowStyles: { fillColor: [240, 240, 240] },
            });

            currentY = doc.lastAutoTable.finalY + 20;

            // 4. Top Risks
            doc.text('3. Active Threats', 15, currentY);

            autoTable(doc, {
                startY: currentY + 5,
                head: [['ID', 'Severity', 'Description', 'Owner']],
                body: [
                    ['GHSA-234-567', 'CRITICAL', 'RCE in Authentication Service', 'Identity Team'],
                    ['AWS-IAM-099', 'HIGH', 'Over-permissive S3 Bucket', 'Cloud Ops'],
                    ['SOC2-CTL-04', 'MEDIUM', 'Missing Audit Logs for Policy Change', 'Completed (Verify)'],
                ],
                theme: 'striped',
                headStyles: { fillColor: [220, 38, 38] }, // Red header for threats
            });

            // Footer
            const pageCount = doc.getNumberOfPages();
            for (let i = 1; i <= pageCount; i++) {
                doc.setPage(i);
                doc.setFontSize(10);
                doc.setTextColor(150);
                doc.text(`Page ${i} of ${pageCount}`, 105, 285, { align: 'center' });
                doc.text('Generated by AstraOS', 105, 290, { align: 'center' });
            }

            doc.save(`CISO_Report_${new Date().toISOString().slice(0, 10)}.pdf`);

        } catch (err) {
            console.error(err);
        } finally {
            setIsGenerating(false);
        }
    };

    return (
        <Button
            variant="outline"
            className="gap-2 border-zinc-700 bg-zinc-900/50 hover:bg-zinc-800 text-zinc-300 hover:text-white transition-all"
            onClick={generateReport}
            disabled={isGenerating}
        >
            {isGenerating ? <Loader2 className="w-4 h-4 animate-spin" /> : <FileDown className="w-4 h-4" />}
            {isGenerating ? 'GENERATING...' : 'EXPORT BOARD PACK'}
        </Button>
    );
}
